'use strict';
const assert=require('node:assert/strict');
const {chromium}=require('playwright');
const BASE=process.env.ELEC_TEST_URL||'http://127.0.0.1:8000/electricien/';
async function change(page,selector,value){
  const el=page.locator(selector);
  await el.fill(String(value));await el.press('Tab');
}
async function run(){
  const browser=await chromium.launch({headless:true});
  try{
    const desktop=await browser.newContext({viewport:{width:1440,height:900}});
    const page=await desktop.newPage();
    const consoleErrors=[],failedAssets=[];
    page.on('pageerror',e=>consoleErrors.push(e.message));
    page.on('response',response=>{
      if(response.status()>=400 && /\.(js|css)(\?|$)/i.test(response.url()))failedAssets.push(response.url()+' '+response.status());
    });
    await page.goto(BASE,{waitUntil:'networkidle'});
    await page.locator('#content h1').waitFor();
    assert((await page.locator('button[data-step]').count())===6,'six steps');
    await change(page,'input[data-path="installation.surface"]',120);
    assert.equal(await page.locator('input[data-path="installation.surface"]').inputValue(),'120');
    await page.locator('button[data-step="1"]').click();
    await change(page,'input[data-path="rooms.chambre"]',4);
    await page.locator('button[data-step="2"]').click();
    assert.equal(await page.locator('select[data-catalog-finition="priseSimple"]').inputValue(),'blanc','default price averages white outlets');
    await change(page,'input[data-path="pointOverrides.generalSockets"]',26);
    await change(page,'input[data-path="pointOverrides.kitchenSockets"]',6);
    await change(page,'input[data-path="appareillage.socketDistribution.double"]',4);
    await change(page,'input[data-path="appareillage.socketDistribution.triple"]',2);
    assert((await page.locator('#content').innerText()).includes('18 simple(s)'),'socket equivalence');
    await change(page,'input[data-path="pointOverrides.simple"]',3);
    await change(page,'input[data-path="pointOverrides.vv"]',2);
    await change(page,'input[data-path="pointOverrides.three"]',1);
    assert((await page.locator('.surfacebox').filter({hasText:'Commandes retenues'}).innerText()).includes('10'),'lighting commands 3+4+3');
    assert((await page.locator('.surfacebox').filter({hasText:'Points lumineux retenus'}).innerText()).includes('6'),'lighting points 3+2+1');
    await page.locator('button[data-step="3"]').click();
    await page.locator('select[data-path="circuits.vmcType"]').selectOption('auto');
    assert((await page.locator('#content').innerText()).includes('3 bouches comprises dans le forfait VMC'),'visible VMC included mouths');
    await change(page,'input[data-path="circuits.vmcExtraMouths"]',1);
    assert((await page.locator('#content').innerText()).includes('Total prévu : 4 bouches'),'VMC three included plus one manually added');
    await page.locator('button[data-step="1"]').click();
    await change(page,'input[data-path="rooms.wc"]',2);
    await page.locator('button[data-step="3"]').click();
    assert((await page.locator('#content').innerText()).includes('Total prévu : 5 bouches'),'second WC generates extra 115 euros');
    await page.locator('button[data-step="2"]').click();
    assert.equal(await page.locator('input[data-path="pointOverrides.vv"]').inputValue(),'2','lighting state saved');
    await page.locator('[data-reset-lighting]').click();
    assert.equal(await page.locator('input[data-path="pointOverrides.vv"]').inputValue(),'','lighting reset to AUTO');
    await change(page,'input[data-path="pointOverrides.simple"]',3);
    await change(page,'input[data-path="pointOverrides.vv"]',2);
    await change(page,'input[data-path="pointOverrides.three"]',1);
    await page.locator('select[data-catalog-brand="priseSimple"]').selectOption('Legrand');
    await page.locator('select[data-catalog-gamme="priseSimple"]').selectOption('Mosaic');
    const mosaic=await page.locator('select[data-catalog-choice="priseSimple"] option').allTextContents();
    assert(mosaic.some(x=>x.includes('278111L-1121-C')&&x.includes('Prix à compléter')),'Mosaic white reference without invented price');
    await page.locator('select[data-catalog-gamme="priseSimple"]').selectOption('Dooxie');
    const online=await page.evaluate(()=>window.SpeedArtiCatalogueEnLigne);
    assert.equal(online.status,'ready','online curated JSON loaded');
    assert(online.added>=33,'catalogue V6.5 loaded with original appendice and new references');
    assert(online.updated>=138,'historical sources updated'); assert.equal(online.invalid,0,'no rejected curated row');
    assert.equal(await page.locator('select[data-catalog-finition="priseSimple"]').inputValue(),'blanc','white preselected for simple sockets');
    const choices=page.locator('select[data-catalog-choice="priseSimple"] option');
    assert(await choices.count()>1,'Dooxie models');
    assert((await choices.allTextContents()).some(t=>t.includes('600335-111-C')),'white Dooxie reference exposed');
    await page.locator('select[data-catalog-brand="priseSimple"]').selectOption('Hager');
    await page.locator('select[data-catalog-gamme="priseSimple"]').selectOption('Essensya');
    assert((await page.locator('select[data-catalog-choice="priseSimple"] option').allTextContents()).some(t=>t.includes('WE100P')),'white Essensya WE100P exposed');
    await page.locator('select[data-catalog-choice="priseSimple"]').selectOption('WEB-2026-005');
    assert((await page.locator('#content').innerText()).includes('WE100P'),'exact Hager brand reference selected');
    assert((await page.locator('#content').innerText()).includes('WE100 + WE401'),'manufacturer BOM visible');
    await page.locator('select[data-catalog-brand="vaEtVient"]').selectOption('Hager');
    await page.locator('select[data-catalog-gamme="vaEtVient"]').selectOption('Essensya');
    const vvOptions=await page.locator('select[data-catalog-choice="vaEtVient"] option').allTextContents();
    assert(vvOptions.some(t=>t.includes('WE001P')),'complete Hager switch available');
    assert(!vvOptions.some(t=>t.includes('WE010P')),'permutator is not a switch');
    await page.locator('select[data-catalog-brand="permutateur"]').selectOption('Hager');
    await page.locator('select[data-catalog-gamme="permutateur"]').selectOption('Essensya');
    const perOptions=await page.locator('select[data-catalog-choice="permutateur"] option').allTextContents();
    assert(perOptions.some(t=>t.includes('WE010P')),'permutator complete Hager selectable');
    assert((await page.locator('a[href*="elec44.fr"]').count())>0,'vendor link for verified reference');
    await page.locator('select[data-catalog-brand="priseSimple"]').selectOption('Legrand');
    await page.locator('select[data-catalog-gamme="priseSimple"]').selectOption('Dooxie');
    await page.locator('select[data-catalog-choice="priseSimple"]').selectOption({index:1});
    await page.locator('select[data-catalog-brand="interrupteur"]').selectOption('Schneider Electric');
    await page.locator('select[data-catalog-gamme="interrupteur"]').selectOption('Odace');
    await page.locator('select[data-catalog-brand="rj45"]').selectOption('Hager');
    await page.locator('select[data-catalog-gamme="rj45"]').selectOption('Gallery');
    await page.locator('select[data-catalog-brand="tv"]').selectOption('Legrand');
    await page.locator('button[data-step="0"]').click();
    await page.locator('button[data-step="2"]').click();
    assert.equal(await page.locator('select[data-catalog-brand="priseSimple"]').inputValue(),'Legrand','state retained');
    assert.equal(await page.locator('input[data-path="appareillage.socketDistribution.double"]').inputValue(),'4','blocks retained');
    await page.locator('#calcBtn').click();
    assert((await page.locator('#content').innerText()).includes('Résultat du chiffrage'));
    assert((await page.locator('#content').innerText()).includes('3 bouches comprises'),'VMC package shown in final result');
    assert((await page.locator('#content').innerText()).includes('Va-et-vient'),'detailed lighting in result');
    assert((await page.locator('#content').innerText()).includes('Permutateurs'),'permutator supplies in result');
    await page.reload({waitUntil:'networkidle'});
    assert((await page.locator('#content').innerText()).includes('Résultat du chiffrage'),'result state retained');
    assert.deepEqual(consoleErrors,[],'no JavaScript page errors');
    assert.deepEqual(failedAssets,[],'no missing JS/CSS resources');
    console.log('PASS Desktop 1440: navigation, AUTO/manual, sockets, 4 catalogue families, persistence, calculation');

    const mobile=await browser.newContext({viewport:{width:390,height:844},isMobile:true,hasTouch:true});
    const phone=await mobile.newPage();
    const phoneErrors=[];
    phone.on('pageerror',e=>phoneErrors.push(e.message));
    await phone.goto(BASE,{waitUntil:'networkidle'});
    await phone.locator('button[data-set="installation.type"][data-value="renovation"]').click();
    await phone.locator('button[data-step="2"]').click();
    await change(phone,'input[data-path="pointOverrides.simple"]',1);
    await change(phone,'input[data-path="pointOverrides.vv"]',1);
    await change(phone,'input[data-path="pointOverrides.three"]',2);
    assert((await phone.locator('.surfacebox').filter({hasText:'Commandes retenues'}).innerText()).includes('9'),'mobile lighting 1+2+6');
    assert(await phone.locator('table.reno-table').count()===1,'reno matrix on mobile');
    await change(phone,'input[data-path="renovation.prises.create"]',1);
    await change(phone,'input[data-path="renovation.routes.prises"]',4);
    await phone.locator('button[data-step="3"]').click();
    await phone.locator('select[data-path="circuits.vmcType"]').selectOption('hygro');
    assert((await phone.locator('#content').innerText()).includes('1 cuisine + 1 WC + 1 salle de bains / salle d’eau'),'mobile VMC included list');
    await phone.locator('input[data-path="circuits.pac"]').check();
    await change(phone,'input[data-path="circuits.pacManual.section"]',6);
    await change(phone,'input[data-path="circuits.pacManual.breaker"]',32);
    await change(phone,'input[data-path="circuits.pacManual.materialPrice"]',100);
    await change(phone,'input[data-path="circuits.pacManual.route"]',15);
    await phone.locator('button[data-step="4"]').click();
    await change(phone,'input[data-path="tableau.panelPrice"]',450);
    await phone.locator('#calcBtn').click();
    assert((await phone.locator('#content').innerText()).includes('Chiffrage provisoire'),'incomplete renovation clearly provisional');
    const width=await phone.evaluate(()=>({body:document.documentElement.scrollWidth,screen:window.innerWidth}));
    assert(width.body<=width.screen+3,'no full-page horizontal overflow: '+JSON.stringify(width));
    assert.deepEqual(phoneErrors,[],'no mobile page errors');
    console.log('PASS Mobile 390: renovation, manual manufacturer, panel, result, no horizontal page overflow');

    await phone.screenshot({path:'electricien-mobile-result.png',fullPage:true});
    await page.screenshot({path:'electricien-desktop-result.png',fullPage:true});
    await desktop.close();await mobile.close();
  }finally{await browser.close();}
}
run().catch(err=>{console.error('FAIL UI',err);process.exitCode=1;});